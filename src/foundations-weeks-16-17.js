const choice = (id, title, prompt, choices, answer, choiceExplanations, hint, explanation) => ({
  id, type: 'choice', title, prompt, choices: choices.map(([optionId, text]) => ({ id: optionId, text })),
  answer, choiceExplanations, hint, explanation,
});
const shortAnswer = (id, title, prompt, acceptedAnswers, hint, explanation) => ({
  id, type: 'short-answer', title, prompt, acceptedAnswers, hint, explanation,
});
const locate = (id, title, prompt, codeLines, answerLines, hint, explanation) => ({
  id, type: 'locate-error', title, prompt, codeLines, answerLines, hint, explanation,
});

const makeDay = (week, number, item) => {
  const prefix = 'foundation-w' + String(week).padStart(2, '0') + '-d' + String(number).padStart(2, '0');
  const entries = [
    { text: item.correct, explanation: item.correctReason, correct: true },
    { text: item.wrong1, explanation: item.wrong1Reason },
    { text: item.wrong2, explanation: item.wrong2Reason },
  ];
  const correctIndex = (week + number) % entries.length;
  const correct = entries.shift();
  entries.splice(correctIndex, 0, correct);
  const choices = entries.map((entry, index) => [String.fromCharCode(97 + index), entry.text]);
  const answer = String.fromCharCode(97 + correctIndex);
  const choiceExplanations = Object.fromEntries(entries.map((entry, index) => [String.fromCharCode(97 + index), entry.explanation]));
  const activities = [
    { time: '15분', title: '계약 구조와 예시 비교', prompt: item.objective + ' 예시에서 관련 조건을 표시해 보세요.' },
    { time: '25분', title: '입력·응답 계약 점검', prompt: item.choicePrompt },
    { time: '20분', title: '불일치 위치 찾기', prompt: item.locatePrompt },
  ];
  return {
    number, title: item.title, objective: item.objective, intro: item.intro, example: item.example, activities,
    exercises: [
      choice(prefix + '-q01', item.title + ' 핵심 판단', item.choicePrompt, choices, answer, choiceExplanations, item.hint, item.correctReason),
      shortAnswer(prefix + '-q02', item.title + ' 단답 확인', item.shortPrompt, item.shortAnswers, item.shortHint, item.shortReason),
      locate(prefix + '-q03', item.title + ' 오류 찾기', item.locatePrompt, item.lines, [item.badLine], item.locateHint, item.locateReason),
    ],
  };
};
const makeWeek = (week, title, objective, intro, points, days) => {
  const sessions = days.map((item, index) => makeDay(week, index + 1, item));
  return {
    id: 'foundation-w' + String(week).padStart(2, '0'), trackId: 'foundations',
    topicId: week === 16 ? 'foundations-api-contracts' : 'foundations-api',
    title, objective, intro, difficulty: '기초', duration: '5일', week, number: week, stage: 2,
    referenceVersion: 'RFC 8259 · RFC 9110 · RFC 9457 · OpenAPI Specification 3.2.1',
    versionReviewedAt: week <= 17 ? '2026-10-16' : '2026-10-13', contentReviewStatus: '문항 검수 완료',
    prerequisiteLessonIds: ['foundation-w' + String(week - 1).padStart(2, '0')],
    points, example: sessions[0].example, studyDays: sessions, sessions,
    exercises: sessions.flatMap((session) => session.exercises),
  };
};

